# Compact this demo's HLSL without changing shader operations. The build verifies
# identical stripped FXC bytecode before embedding the source for D3DCompile.
param(
    [Parameter(Mandatory=$true)][string]$InputPath,
    [Parameter(Mandatory=$true)][string]$OutputHeader,
    [Parameter(Mandatory=$true)][string]$FxcPath
)
$ErrorActionPreference = 'Stop'
$Rename = $true
$OutputHeader = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputHeader)
$outputDirectory = Split-Path -Parent $OutputHeader
New-Item -ItemType Directory -Force -Path $outputDirectory | Out-Null
$OutputPath = Join-Path $outputDirectory 'Terrain.compact.hlsl'
$source = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $InputPath))
$source = [regex]::Replace($source,'(?s)/\*.*?\*/|//[^\r\n]*',' ')
if ($source.Contains('"') -or $source.Contains('#')) { throw 'This compact source path expects no strings or preprocessor directives' }
$used = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
foreach ($match in [regex]::Matches($source,'[A-Za-z_][A-Za-z_0-9]*')) { [void]$used.Add($match.Value) }
$names = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
foreach ($match in [regex]::Matches($source,'\b(?:void|bool|int|uint[1-4]?|float[1-4]?|cbuffer|RWTexture2D\s*<[^>]+>)\s+([A-Za-z_][A-Za-z_0-9]*)')) {
    if ($match.Groups[1].Value.Length -gt 1 -and $match.Groups[1].Value -ne 'CS_Terrain') { [void]$names.Add($match.Groups[1].Value) }
}
$mapping = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::Ordinal)
if ($Rename) {
    $candidates = @((65..90 + 97..122) | ForEach-Object { [string][char]$_ })
    foreach ($first in 65..90) { foreach ($last in 65..90) { $candidates += ([string][char]$first)+([string][char]$last) } }
    $cursor = 0
    foreach ($name in ($names | Sort-Object { -([regex]::Matches($source,'\b'+[regex]::Escape($_)+'\b').Count*$_.Length) })) {
        while ($used.Contains($candidates[$cursor])) { ++$cursor }
        $mapping.Add($name,$candidates[$cursor]); [void]$used.Add($candidates[$cursor]); ++$cursor
    }
}
$tokenPattern = '(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?[fFuU]?|[A-Za-z_][A-Za-z_0-9]*|\+\+|--|<<|>>|<=|>=|==|!=|&&|\|\||\+=|-=|\*=|/=|%=|&=|\|=|\^=|[^\s]'
$text = New-Object Text.StringBuilder
$previous = ''
foreach ($match in [regex]::Matches($source,$tokenPattern)) {
    $token = $match.Value
    if ($previous -ne '.' -and $mapping.ContainsKey($token)) { $token = $mapping[$token] }
    if ($token -match '^\d+\.0+$') { $token = $token.Substring(0,$token.IndexOf('.')+1) }
    if ($token -match '^0\.\d') { $token = $token.Substring(1) }
    if (($previous -match '[A-Za-z_0-9]$' -and $token -match '^[A-Za-z_0-9]') -or
        ($previous+$token -in @('++','--','<<','>>','<=','>=','==','!=','&&','||','+=','-=','*=','/=','%=','&=','|=','^=','//','/*'))) { [void]$text.Append(' ') }
    [void]$text.Append($token); $previous = $token
}
[IO.File]::WriteAllText($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputPath),$text.ToString(),[Text.Encoding]::ASCII)

$reference = Join-Path $outputDirectory 'Terrain.reference.cso'
$compacted = Join-Path $outputDirectory 'Terrain.compact.cso'
& $FxcPath /nologo /O1 /T cs_5_0 /E CS_Terrain /Fo $reference /Qstrip_reflect /Qstrip_debug $InputPath
if ($LASTEXITCODE) { throw 'Reference shader validation failed' }
& $FxcPath /nologo /O1 /T cs_5_0 /E CS_Terrain /Fo $compacted /Qstrip_reflect /Qstrip_debug $OutputPath
if ($LASTEXITCODE) { throw 'Compact shader validation failed' }
# Compare bytes directly; no dependence on a host's PowerShell module path.
if ([Convert]::ToBase64String([IO.File]::ReadAllBytes($reference)) -ne [Convert]::ToBase64String([IO.File]::ReadAllBytes($compacted))) {
    throw 'Compaction changed shader bytecode; the source will not be embedded.'
}
$shaderText = $text.ToString()
$header = '// Generated by EmbedShader.ps1 from Terrain.hlsl; see LICENSE-Mountains.txt.'+"`r`n"+'static const char terrainSource[] = '
# Keep individual C string tokens short for the VS2019 compiler.
for ($start = 0; $start -lt $shaderText.Length; $start += 1000) {
    $chunk = $shaderText.Substring($start,[Math]::Min(1000,$shaderText.Length-$start))
    $header += '"'+$chunk.Replace('\','\\').Replace('"','\"')+'"'+"`r`n"
}
$header += ';'+"`r`n"
[IO.File]::WriteAllText($OutputHeader,$header,[Text.Encoding]::ASCII)
Write-Host "Embedded $($shaderText.Length) bytes of HLSL; stripped bytecode is identical."
